from pathlib import Path

import numpy as np
import matplotlib.pyplot as plt


# ============================================================
# GLOBAL RECONSTRUCTION
# ============================================================

def plot_solution_with_error(
    x,
    u_exact,
    u_uncorrected,
    u_reconstructed,
    l2_before,
    l2_after,
    improvement,
    run_dir,
):
    """
    Compare exact, uncorrected and reconstructed solutions.

    Parameters
    ----------
    x : ndarray
        Spatial coordinates.

    u_exact : ndarray
        Benchmark solution.

    u_uncorrected : ndarray
        Solution prior to homogeneous correction.

    u_reconstructed : ndarray
        Final weighted reconstruction.

    l2_before : float
        Global error before reconstruction.

    l2_after : float
        Global error after reconstruction.

    improvement : float
        Improvement factor

            l2_before / l2_after.

    run_dir : Path
        Output directory.
    """

    error_before = (
        u_uncorrected
        -
        u_exact
    )

    error_after = (
        u_reconstructed
        -
        u_exact
    )

    fig, ax1 = plt.subplots(
        figsize=(16, 9)
    )

    ax1.plot(
        x,
        u_exact,
        color="black",
        linewidth=4,
        label="Exact solution",
    )

    ax1.plot(
        x,
        u_uncorrected,
        "--",
        color="red",
        linewidth=2,
        label=(
            f"Uncorrected\n"
            f"L2={l2_before:.3e}"
        ),
    )

    ax1.plot(
        x,
        u_reconstructed,
        color="green",
        linewidth=3,
        label=(
            f"Weighted reconstruction\n"
            f"L2={l2_after:.3e}"
        ),
    )

    ax1.set_xlabel(
        "Spatial coordinate x"
    )

    ax1.set_ylabel(
        "Solution u(x)"
    )

    ax1.grid(True)

    ax2 = ax1.twinx()

    ax2.plot(
        x,
        error_before,
        color="darkred",
        linewidth=2,
        alpha=0.8,
        label="Error before",
    )

    ax2.plot(
        x,
        error_after,
        color="darkgreen",
        linewidth=2,
        alpha=0.8,
        label="Error after",
    )

    ax2.set_ylabel(
        "Pointwise Error"
    )

    lines1, labels1 = (
        ax1.get_legend_handles_labels()
    )

    lines2, labels2 = (
        ax2.get_legend_handles_labels()
    )

    ax1.legend(
        lines1 + lines2,
        labels1 + labels2,
        loc="best",
    )

    ax1.set_title(
        "Global Reconstruction\n"
        f"L2 before = {l2_before:.3e}\n"
        f"L2 after  = {l2_after:.3e}\n"
        f"Improvement = {improvement:.2f}x"
    )

    plt.tight_layout()

    plt.savefig(
        Path(run_dir)
        /
        "solution_with_error.png",
        dpi=600,
        bbox_inches="tight",
    )

    plt.close(fig)



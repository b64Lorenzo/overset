def plot_sharp_reconstruction(
    x,
    u_exact,
    u_sharp,
    sharp_error,
    run_dir,
):
    """
    Plot reconstruction assembled using
    a direct interface cut.

    Parameters
    ----------
    x : ndarray
        Coordinates.

    u_exact : ndarray
        Exact benchmark solution.

    u_sharp : ndarray
        Reconstruction using a sharp cut.

    sharp_error : float
        Global L2 error.

    run_dir : Path
        Output directory.
    """

    fig, ax = plt.subplots(
        figsize=(16, 9)
    )

    ax.plot(
        x,
        u_exact,
        color="black",
        linewidth=4,
        label="Exact solution",
    )

    ax.plot(
        x,
        u_sharp,
        color="red",
        linewidth=2,
        linestyle="--",
        label=(
            "Sharp reconstruction\n"
            f"L2={sharp_error:.3e}"
        ),
    )

    ax.grid(True)

    ax.set_xlabel(
        "Spatial coordinate x"
    )

    ax.set_ylabel(
        "Solution u(x)"
    )

    ax.legend()

    ax.set_title(
        "Sharp Interface Reconstruction"
    )

    plt.tight_layout()

    plt.savefig(
        Path(run_dir)
        /
        "sharp_reconstruction.png",
        dpi=600,
        bbox_inches="tight",
    )

    plt.close(fig)



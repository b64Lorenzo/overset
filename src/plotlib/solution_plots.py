# SHARP VS WEIGHTED
# ============================================================

def plot_weight_blending_comparison(
    x,
    u_exact,
    u_sharp,
    u_weighted,
    sharp_error,
    weighted_error,
    weighting_gain,
    run_dir,
):
    """
    Compare sharp and weighted assembly.

    Parameters
    ----------
    x : ndarray
        Coordinates.

    u_exact : ndarray
        Benchmark solution.

    u_sharp : ndarray
        Reconstruction obtained using
        a direct cut at the interface.

    u_weighted : ndarray
        Reconstruction obtained using
        overlap blending.

    sharp_error : float
        L2 error of sharp assembly.

    weighted_error : float
        L2 error of weighted assembly.

    weighting_gain : float
        Improvement

            sharp_error / weighted_error.

    run_dir : Path
        Output directory.
    """

    fig, ax = plt.subplots(
        figsize=(16, 9)
    )

    ax.plot(
        x,
        u_exact,
        color="black",
        linewidth=4,
        label="Exact",
    )

    ax.plot(
        x,
        u_sharp,
        "--",
        color="red",
        linewidth=2,
        label=(
            "Sharp assembly\n"
            f"L2={sharp_error:.3e}"
        ),
    )

    ax.plot(
        x,
        u_weighted,
        color="blue",
        linewidth=3,
        label=(
            "Weighted assembly\n"
            f"L2={weighted_error:.3e}"
        ),
    )

    ax.grid(True)

    ax.set_xlabel(
        "Spatial coordinate x"
    )

    ax.set_ylabel(
        "Solution u(x)"
    )

    txt = (
        f"Sharp error    : {sharp_error:.3e}\n"
        f"Weighted error : {weighted_error:.3e}\n"
        f"Gain           : {weighting_gain:.2f}x"
    )

    ax.text(
        0.02,
        0.98,
        txt,
        va="top",
        transform=ax.transAxes,
        bbox=dict(
            facecolor="white",
            alpha=0.90,
        ),
    )

    ax.legend()

    ax.set_title(
        "Sharp vs Weighted Overlap Assembly"
    )

    plt.tight_layout()

    plt.savefig(
        Path(run_dir)
        /
        "weight_blending_comparison.png",
        dpi=600,
        bbox_inches="tight",
    )

    plt.close(fig)


# ============================================================
# GLOBAL ERROR COMPARISON
# ============================================================

def plot_global_error_comparison(
    x,
    u_exact,
    u_uncorrected,
    u_sharp,
    u_weighted,
    run_dir,
):
    """
    Compare error distributions of the three
    reconstruction stages.

    Parameters
    ----------
    x : ndarray
        Coordinates.

    u_exact : ndarray
        Exact solution.

    u_uncorrected : ndarray
        Solution prior to reconstruction.

    u_sharp : ndarray
        Sharp reconstruction.

    u_weighted : ndarray
        Weighted reconstruction.

    run_dir : Path
        Output directory.
    """

    fig, ax = plt.subplots(
        figsize=(16, 9)
    )

    ax.plot(
        x,
        u_uncorrected - u_exact,
        linewidth=2,
        label="Uncorrected error",
    )

    ax.plot(
        x,
        u_sharp - u_exact,
        linewidth=2,
        label="Sharp error",
    )

    ax.plot(
        x,
        u_weighted - u_exact,
        linewidth=2,
        label="Weighted error",
    )

    ax.grid(True)

    ax.set_xlabel(
        "Spatial coordinate x"
    )

    ax.set_ylabel(
        "Pointwise error"
    )

    ax.legend()

    ax.set_title(
        "Error Evolution Throughout Reconstruction"
    )

    plt.tight_layout()

    plt.savefig(
        Path(run_dir)
        /
        "global_error_comparison.png",
        dpi=600,
        bbox_inches="tight",
    )

    plt.close(fig)